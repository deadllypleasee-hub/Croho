    public static List<Question> level(int level) {
        if (level < 0 || level >= LEVEL_COUNT) throw new IllegalArgumentException("Unknown level");
        return ALL.subList(level * QUESTIONS_PER_LEVEL, (level + 1) * QUESTIONS_PER_LEVEL);
    }

    public static Question byId(int id) { return ALL.get(id); }

    public static List<Question> exam(Random random) {
        List<Question> exam = new ArrayList<>();
        for (int level = 0; level < LEVEL_COUNT; level++) {
            List<Question> pool = new ArrayList<>(level(level));
            Collections.shuffle(pool, random);
            exam.addAll(pool.subList(0, 2));
        }
        Collections.shuffle(exam, random);
        return exam;
    }
